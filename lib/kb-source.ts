// The single knowledge source: the Prolog files listed in kb/manifest.json,
// concatenated into one program, plus facts generated from what the repository
// already records (so nobody restates them by hand), versioned by content hash.
// Shared by the web server and the MCP server, so both always see the same KB.

import { createHash } from "node:crypto";
import { readFile, stat } from "node:fs/promises";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "..");
const MANIFEST = join(ROOT, "kb", "manifest.json");
const PACKAGE = join(ROOT, "package.json");

export interface KbFile {
  name: string;
  lines: number;
  sha: string;
  modified: number;
}

export interface Kb {
  version: string;
  loadedAt: number;
  files: KbFile[];
  program: string;
}

const sha = (text: string, n: number) => createHash("sha1").update(text).digest("hex").slice(0, n);

export async function loadKb(): Promise<Kb> {
  const { sources } = JSON.parse(await readFile(MANIFEST, "utf8")) as { sources: string[] };
  const files: KbFile[] = [];
  const parts: string[] = [];
  for (const rel of sources) {
    const path = join(ROOT, rel);
    let text = await readFile(path, "utf8");
    if (!text.endsWith("\n")) text += "\n";
    files.push({
      name: rel,
      lines: text.split("\n").length - 1,
      sha: sha(text, 10),
      modified: Math.floor((await stat(path)).mtimeMs / 1000),
    });
    parts.push(`% ===== ${rel} =====\n${text}`);
  }
  parts.push(await generatedFacts(sources));
  const program = parts.join("\n");
  return { version: sha(program, 12), loadedAt: Math.floor(Date.now() / 1000), files, program };
}

const atom = (s: string) => `'${s.replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;

/** kb_file/2 from the manifest and package_version/2 from package.json (see kb/system.pl). */
async function generatedFacts(sources: string[]): Promise<string> {
  const pkg = JSON.parse(await readFile(PACKAGE, "utf8")) as Record<string, Record<string, string> | undefined>;
  const packages = { ...pkg.dependencies, ...pkg.devDependencies };
  return [
    "% ===== generated by lib/kb-source.ts from kb/manifest.json and package.json =====",
    ...sources.map((f) => `kb_file(knowledge_base, ${atom(f)}).`),
    ...Object.entries(packages).map(([name, version]) => `package_version(${atom(name)}, ${atom(version)}).`),
    "",
  ].join("\n");
}
